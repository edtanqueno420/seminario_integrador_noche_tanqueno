print("Comparacion de stock en almacen")

stock_actual = float(input("Ingrese el stock actual: "))
stock_minimo = float(input("Ingrese el stock minimo: "))
print(stock_actual, "==", stock_minimo, stock_actual == stock_minimo)

print(stock_actual, "!=", stock_minimo, stock_actual != stock_minimo)

print(stock_actual, ">", stock_minimo, stock_actual > stock_minimo)

print(stock_actual, "<", stock_minimo, stock_actual < stock_minimo)

print(stock_actual, ">=", stock_minimo, stock_actual >= stock_minimo)

print(stock_actual, "<=", stock_minimo, stock_actual <= stock_minimo)
